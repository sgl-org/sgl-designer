        private static void DeclareEventHandlersRecursive(IEnumerable<SglWidgetData> widgets, StringBuilder sb)
        {
            foreach (var w in widgets)
            {
                // 只有当设置了事件入口名，或者 EventRoutes 字典不为空时才生成
                if (w.IsClickable || w.EventRoutes.Count > 0)
                {
                    string handlerName = string.IsNullOrWhiteSpace(w.EventCallbackName)
                                         ? $"{w.Id}_event_handler"
                                         : w.EventCallbackName;

                    sb.AppendLine($"void {handlerName}(sgl_event_t *event);");
                }

                if (w.Children?.Count > 0)
                    DeclareEventHandlersRecursive(w.Children, sb);
            }
        }
