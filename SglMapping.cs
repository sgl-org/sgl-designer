                }

                if (widget.Children != null && widget.Children.Count > 0)
                {
                    DeclareAllWidgetsRecursive2(widget.Children, sb, declaredIds);
                }
            }
        }

        // 专门用于递归导出全局变量的方法
        private static void GenerateGlobalVariables(SglWidgetData widget, StringBuilder sbVars)
        {
            if (widget is SglBarchartData chart)
            {
                string labelVarName = $"{chart.Tag}_labels";
                string valueVarName = $"{chart.Tag}_values";

                // 导出 X 轴标签数组 (数量随 chart.XLabelCount 变化)
                var labels = Enumerable.Range(0, chart.XLabelCount)
                                       .Select(i => $"\"{(char)('A' + i % 26)}\"");
                sbVars.AppendLine($"const char* {labelVarName}[] = {{ {string.Join(", ", labels)} }};");

                // 2. 导出数值数组 (基于当前的 YMax/YMin 计算预览值)
                var values = Enumerable.Range(0, chart.XLabelCount)
                    .Select(i =>
                    {
                        double percent = 0.3 + (i * 0.15) % 0.6;
                        return (int)(chart.YMin + (chart.YMax - chart.YMin) * percent);
                    });
                sbVars.AppendLine($"int32_t {valueVarName}[] = {{ {string.Join(", ", values)} }};");
                sbVars.AppendLine();
            }
            else if (widget is SglLinechartData linechart)
            {
                string labelVarName = $"{linechart.Tag}_labels";
                string valueVarName = $"{linechart.Tag}_pts";
                IEnumerable<int> values = (linechart.Values != null && linechart.Values.Count > 0)
                    ? linechart.Values
                    : new[] { 0 };
                var labels = values.Select((v, i) => $"\"{i}\"");

                sbVars.AppendLine($"const char* {labelVarName}[] = {{ {string.Join(", ", labels)} }};");
                sbVars.AppendLine($"int32_t {valueVarName}[] = {{ {string.Join(", ", values)} }};");
                sbVars.AppendLine();
            }
            // 递归子节点
            foreach (var child in widget.Children) GenerateGlobalVariables(child, sbVars);
        }
        // 生成单个屏幕的 C 代码
        public static string ConvertPageToCode(SglPageData page)
        {
            StringBuilder sbVars = new StringBuilder(); // 全局变量区
            StringBuilder sb = new StringBuilder();

            //sb.AppendLine($"sgl_obj_t* {page.Id}; // 全局句柄\n");
            sbVars.AppendLine($"#include \"ui.h\"\n");
            // 找到根容器
            var root = page.Widgets.FirstOrDefault(w => w.Parent == null);
            if (root != null)
            {
                // 强制给根容器分配 Tag，确保和页面 ID 一致
                root.Tag = page.Id;

                // --- 1. 使用递归扫描所有控件，生成全局变量定义 ---
                GenerateGlobalVariables(root, sbVars);

                // 导出全局变量

                sb.AppendLine($"sgl_obj_t* ui_{page.Id}_init(void) {{");

                // 2. 生成根容器代码
                // 注意：这里手动处理第一行，不带类型声明，直接赋值给全局变量
                sb.AppendLine($"    // --- {page.Id} ---");
                sb.AppendLine($"    {page.Id} = sgl_rect_create(NULL);"); // 去掉 sgl_obj_t*

                var scr = root as SglPanelData;

                //  生成根容器的其他属性 (SetSize, SetPos 等)
                // 可以稍微修改 GenerateSglCode，或者在这里手动拼剩下的
                sb.AppendLine($"    sgl_obj_set_size({page.Id}, {root.W}, {root.H});");
                sb.AppendLine($"    sgl_obj_set_pos({page.Id}, {root.X}, {root.Y});");
                //sb.AppendLine($"//    sgl_obj_set_border_width({page.Id},{scr.BorderWidth});");
                //sb.AppendLine($"//    sgl_obj_set_border_Color({page.Id},{scr.BorderColor});");
                sb.AppendLine($"    sgl_rect_set_color({page.Id}, {sgl_rgb(scr.BgColor)});");
                sb.AppendLine($"    sgl_rect_set_alpha({page.Id}, {scr.Opacity});");
                sb.AppendLine($"    sgl_rect_set_radius({page.Id}, {scr.Radius});");
                sb.AppendLine($"    sgl_rect_set_border_width({page.Id}, {scr.BorderWidth});");
                sb.AppendLine($"    sgl_rect_set_border_color({page.Id}, {sgl_rgb(scr.BorderColor)});");
                // 2. 设置图像资源 (pixmap)
                if (!string.IsNullOrEmpty(scr.PixmapVarName))
                {
                    sb.AppendLine($"    sgl_rect_set_pixmap({scr.Id}, &{scr.Id}_{scr.PixmapVarName}_pixmap);");
                }
                // 2. 遍历子控件，此时 parentName 传入 page.Id
                //  递归生成子控件
                if (root.Children.Count > 0)
                {
                    sb.AppendLine($"    // Children of {page.Id}");
                    foreach (var child in root.Children)
                    {
                        // 传入根容器的变量名作为父节点
                        sb.Append(SglMapping.GenerateSglCode(child, page.Id));
                    }
                }
            }

            sb.AppendLine($"\n  return {page.Id};");
            sb.AppendLine("}");
            return sbVars.ToString() + "\n" + sb.ToString();
        }


        public static string GenerateSglCode(SglWidgetData d, string parentName = "screen")
        {
            StringBuilder sb = new StringBuilder();
            string name = d.Id;
            string type = d.Type.ToString().ToLower();

            sb.AppendLine($"    // --- {name} ---");

            // 创建对象，使用传入的 parentName
            if (d is SglBoxData)
            {
                sb.AppendLine($"    {name} = sgl_box_create({parentName});");
            }
            else if (d is SglPanelData || d.Type == SglMapping.SglType.Rectangle)
            {
                sb.AppendLine($"    {name} = sgl_rect_create({parentName});");
            }
            else
            {
                sb.AppendLine($"    {name} = sgl_{type}_create({parentName});");
            }
            sb.AppendLine($"    sgl_obj_set_size({name}, {d.W}, {d.H});");
            sb.AppendLine($"    sgl_obj_set_pos({name}, {d.X}, {d.Y});");
            if(d.IsHidden)
            {
                sb.AppendLine($"    sgl_obj_set_hidden({name});");
            }
            if (d is SglButtonData btn)
            {
                // 映射 sgl_button_set_color (主体色)
                sb.AppendLine($"    sgl_button_set_color({name}, {sgl_rgb(btn.BgColor)});");

                // 映射 sgl_button_set_text
                sb.AppendLine($"    sgl_button_set_text({name}, \"{btn.Text}\");");

                sb.AppendLine($"    sgl_button_set_font({name}, &{btn.FontName});");

                // 映射 sgl_button_set_text_color
                sb.AppendLine($"    sgl_button_set_text_color({name}, {sgl_rgb(btn.TextColor)});");

                // 映射 sgl_button_set_alpha
                sb.AppendLine($"    sgl_button_set_alpha({name}, {btn.Opacity});");

                // 映射 sgl_button_set_radius (调用底层 sgl_obj_set_radius)
                if (btn.Radius > 0)
                    sb.AppendLine($"    sgl_button_set_radius({name}, {btn.Radius});");

                // 映射 sgl_button_set_border (如果有宽度)
                if (btn.BorderWidth > 0)
                {
                    sb.AppendLine($"    sgl_button_set_border_width({name}, {btn.BorderWidth});");
                    sb.AppendLine($"    sgl_button_set_border_color({name}, {sgl_rgb(btn.BorderColor)});");
