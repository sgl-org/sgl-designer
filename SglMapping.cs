            {
                // 注意：如果之前根据类型分了 pixmap 和 icon_pixmap，这里要对应处理
                // 假设图标用 sgl_icon_pixmap_t，普通图片用 sgl_pixmap_t
                if (imgVar.StartsWith("ico_"))
