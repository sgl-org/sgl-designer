        private static void DeclareAllWidgetsRecursive(IEnumerable<SglWidgetData> widgets, StringBuilder sb, HashSet<string> declaredIds)
        {
            if (widgets == null) return;

            foreach (var widget in widgets)
            {
                // 检查是否已经声明过（防止重复声明屏幕 ID 或同名控件）
                if (!string.IsNullOrEmpty(widget.Id) && !declaredIds.Contains(widget.Id))
                {
                    sb.AppendLine($"extern sgl_obj_t* {widget.Id};");
                    declaredIds.Add(widget.Id);
                }

                if (widget.Children != null && widget.Children.Count > 0)
                {
                    DeclareAllWidgetsRecursive(widget.Children, sb, declaredIds);
                }
            }
        }
        private static void DeclareAllWidgetsRecursive2(IEnumerable<SglWidgetData> widgets, StringBuilder sb, HashSet<string> declaredIds)
        {
            if (widgets == null) return;

            foreach (var widget in widgets)
            {
                // 检查是否已经声明过（防止重复声明屏幕 ID 或同名控件）
                if (!string.IsNullOrEmpty(widget.Id) && !declaredIds.Contains(widget.Id))
