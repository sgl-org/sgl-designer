        // --- 核心转换逻辑：RGB888 (WPF) -> RGB565 (Embedded) ---
        private static string sgl_rgb(Color c)
        {
            //// R: 取高 5 位 (8位右移3位)
            //// G: 取高 6 位 (8位右移2位)
            //// B: 取高 5 位 (8位右移3位)
            //ushort r = (ushort)((c.R >> 3) & 0x1F);
            //ushort g = (ushort)((c.G >> 2) & 0x3F);
            //ushort b = (ushort)((c.B >> 3) & 0x1F);

            //// 拼接：RRRRR GGGGGG BBBBB
            //int rgb565 = (r << 11) | (g << 5) | b;

            // 关键点：不再直接返回 0xFFFF，而是返回 sgl_color_make16(0xFFFF)
            // 这样 C 语言编译器就会识别为 sgl_color16_t 类型
            return $"sgl_rgb(0x{c.R:X2}, 0x{c.G:X2}, 0x{c.B:X2})";
        }

