        // 生成事件处理函数的 C 语言模板
        public static string GenerateCEventHandlers(SglWidgetData d, HashSet<string> processed)
        {
            // 如果该控件没有任何定义的事件，直接处理子控件并返回
            if (d.Events == null || d.Events.Count == 0)
            {
                StringBuilder childSb = new StringBuilder();
                foreach (var child in d.Children)
                    childSb.Append(GenerateCEventHandlers(child, processed));
                return childSb.ToString();
            }

            StringBuilder sb = new StringBuilder();
            // 生成外部函数头文件
            foreach (var eventItem in d.Events)
            {
                if (eventItem?.Actions == null) continue;

                foreach (var action in eventItem.Actions)
                {
                    if (action == null) continue;

                    // 根据动作的真实类型进行匹配
                    // 如果 action 的实例是 SglCallFunctionAction，则将其重命名为 callAct
                    if (action is SglCallFunctionAction callAct)
                    {
                        // 访问子类特有的属性（假设子类里定义的属性叫 FunctionName）
                        if (!string.IsNullOrEmpty(callAct.FuncName))
                        {
                            // 检查是否已经添加过，避免重复 extern（可选）
                            string funcLine = $"extern void {callAct.FuncName}(sgl_event_t* e);";
                            if (!sb.ToString().Contains(funcLine))
                            {
                                sb.AppendLine(funcLine);
                            }
                        }
                    }
                    // 如果以后有其他需要生成头文件的动作类型，可以在这里继续 else if
                }
            }
            // 生成具体的事件处理函数（Stub）
            foreach (var eventItem in d.Events)
            {
                if (eventItem == null) continue;

                // 生成事件处理函数名
                string handlerName = $"{d.Id}_{eventItem.Trigger.ToString().ToLower()}";

                // 避免重复生成同一个函数
                if (!processed.Contains(handlerName))
                {
                    sb.AppendLine($"// {d.Id} 控件的 {eventItem.Trigger} 事件处理");
                    sb.AppendLine($"sgl_weak_fn void {handlerName}(sgl_event_t *e)");
                    sb.AppendLine("{");
                    sb.AppendLine($"\n   SGL_LOG_INFO(\"{d.Id} {eventItem.Trigger.ToString().ToLower()}\");");


                    // 生成动作代码
                    if (eventItem.Actions != null && eventItem.Actions.Count > 0)
                    {
                        int actionIndex = 1;
                        foreach (var action in eventItem.Actions)
                        {
                            if (action == null) continue;

                            sb.AppendLine($"    // Action {actionIndex}: {action.ActionType}");

                            // 使用 C# 的模式匹配直接转换类型并访问属性
                            switch (action)
                            {
                                // 调用函数
                                case SglCallFunctionAction callAct:
                                    if (!string.IsNullOrEmpty(callAct.FuncName))
                                        sb.AppendLine($"    {callAct.FuncName}(e);");
                                    else
                                        sb.AppendLine($"    // 请指定函数名");
                                    break;

                                // 2. 切换屏幕
                                case SglChangeScreenAction changeAct:
                                    if (!string.IsNullOrEmpty(changeAct.TargetPage))
                                    {
                                        // 防御性检查：验证目标屏幕仍然存在
                                        bool pageExists = SglScreen.Instance.ScreenList
                                            .Any(s => s.Id.Equals(changeAct.TargetPage, StringComparison.OrdinalIgnoreCase));
                                        if (pageExists)
                                            sb.AppendLine($"    ui_screen_load(UI_{changeAct.TargetPage.ToUpper()});");
                                        else
                                            sb.AppendLine($"    // 警告: 目标屏幕 \"{changeAct.TargetPage}\" 已被删除");
                                    }
                                    else
                                        sb.AppendLine($"    // 请指定目标屏幕ID");
                                    break;

                                //  修改属性
                                case SglSetPropertyAction setPropAct:
                                    if (setPropAct.Target != null && !string.IsNullOrEmpty(setPropAct.Value))
                                        sb.AppendLine($"    ui_obj_set_property({setPropAct.Target}, {setPropAct.PropertyType.ToString().ToUpper()}, {setPropAct.Value});");
                                    else
                                        sb.AppendLine($"    // 请指定目标ID、属性名和值");
                                    break;

                                //  修改标志 (Flag)
                                case SglModifyFlagAction flagAct:
                                    // 假设子类有 TargetId 和具体的 Flag 属性
                                    if (flagAct.Target != null)
                                        sb.AppendLine($"    ui_obj_set_flag({flagAct.Target}, {flagAct.FlagType.ToString().ToUpper()});");
                                    else
                                        sb.AppendLine($"    // 请指定目标ID");
                                    break;

                                default:
                                    sb.AppendLine($"    // 未实现的动作类型: {action.ActionType}");
                                    break;
                            }
                            actionIndex++;
                        }
                    }
                    else
                    {
                        sb.AppendLine("    // 没有定义动作");
                    }

                    sb.AppendLine("}\n");
                    processed.Add(handlerName);
                }
            }

            // 2. 生成总入口分发函数（如果控件有事件回调名）
            if (!string.IsNullOrEmpty(d.EventCallbackName))
            {
                sb.AppendLine($"// {d.Id} 的事件分发路由函数");
                sb.AppendLine($"void {d.EventCallbackName}(sgl_event_t *event) {{");
                sb.AppendLine("    switch(event->type) {");

                foreach (var eventItem in d.Events)
                {
                    if (eventItem == null) continue;

                    // 将枚举转为 SGL 宏格式
                    string eventEnumName = eventItem.Trigger.ToString().ToSnakeCase().ToUpper();
                    string macroName = $"SGL_EVENT_{eventEnumName}";

                    string handlerName = $"{d.Id}_{eventItem.Trigger.ToString().ToLower()}";

                    sb.AppendLine($"        case {macroName}:");
                    sb.AppendLine($"            {handlerName}(event);");
                    sb.AppendLine($"            break;");
                }

                sb.AppendLine("        default: break;");
                sb.AppendLine("    }");
                sb.AppendLine("}\n");
            }

            //  生成事件绑定代码
            //sb.AppendLine($"// 绑定 {d.Id} 的事件处理器");
            //sb.AppendLine($"void bind_{d.Id}_events(sgl_obj_t* obj) {{");

