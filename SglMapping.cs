                if (!declaredIds.Contains(screen.Id))
                {
                    sb.AppendLine($"extern sgl_obj_t* {screen.Id};");
                    declaredIds.Add(screen.Id);
                }

                // 递归处理子控件，同时传递 HashSet
                DeclareAllWidgetsRecursive(screen.Widgets, sb, declaredIds);
                sb.AppendLine("");
            }

            //  初始化函数声明
            sb.AppendLine("// --- Init Functions ---");
